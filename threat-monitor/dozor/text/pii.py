"""Защита персональных данных.

* Телефоны и адреса электронной почты в сохраняемых фрагментах маскируются.
* Поисковые запросы по телефонам и e-mail отклоняются: система не
  используется для установления личности, поиска аккаунтов и объединения
  сведений о человеке между платформами (п. 2 политики).
* Запросы, похожие на ФИО, допускаются только как поиск сообщений, где
  имя упомянуто; пользователь видит предупреждение, запрос журналируется.
"""

from __future__ import annotations

import re

EMAIL_RE = re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+", re.UNICODE)
# 9–15 цифр с разделителями: +998 90 123-45-67, 8 (701) 123 45 67 и т. п.
PHONE_RE = re.compile(r"(?<![\w])\+?\d(?:[\s\-().]*\d){8,14}(?![\w])")
# Идентификаторы документов вида AA1234567 (паспорт) и ИНН/ПИНФЛ (12–14 цифр) —
# в запросах не допускаются по той же причине.
DOC_ID_RE = re.compile(r"(?<![\w])(?:[A-ZА-Я]{2}\s?\d{7}|\d{12,14})(?![\w])")

_NAME_RE = re.compile(
    r"(?<![\w])[A-ZА-ЯЁЎҚҒҲӘӨҮҰІҢҶӢӮ][a-zа-яёўқғҳәөүұіңҷӣӯ'ʻ’-]{1,}\s+[A-ZА-ЯЁЎҚҒҲӘӨҮҰІҢҶӢӮ][a-zа-яёўқғҳәөүұіңҷӣӯ'ʻ’-]{1,}"
)


class QueryPolicyError(ValueError):
    """Запрос нарушает политику использования."""


def mask_pii(text: str) -> tuple[str, dict[str, int]]:
    counts = {"email": 0, "phone": 0}

    def _email(_m: re.Match) -> str:
        counts["email"] += 1
        return "[e-mail скрыт]"

    def _phone(m: re.Match) -> str:
        digits = sum(c.isdigit() for c in m.group(0))
        # Даты, время и короткие числа — не телефоны
        if digits < 9:
            return m.group(0)
        counts["phone"] += 1
        return "[телефон скрыт]"

    text = EMAIL_RE.sub(_email, text or "")
    text = PHONE_RE.sub(_phone, text)
    return text, counts


def check_query(query: str) -> None:
    if EMAIL_RE.search(query or ""):
        raise QueryPolicyError(
            "Поиск по адресам электронной почты запрещён политикой системы: "
            "контакты не используются для установления личности, поиска аккаунтов "
            "или объединения сведений о человеке."
        )
    if PHONE_RE.search(query or ""):
        raise QueryPolicyError(
            "Поиск по номерам телефонов запрещён политикой системы: "
            "контакты не используются для установления личности, поиска аккаунтов "
            "или объединения сведений о человеке."
        )
    if DOC_ID_RE.search(query or ""):
        raise QueryPolicyError(
            "Поиск по номерам документов и персональным идентификаторам запрещён политикой системы."
        )


def person_name_notice(query: str) -> str | None:
    if _NAME_RE.search(query or ""):
        return (
            "Запрос похож на имя человека. Будут найдены только публичные сообщения, "
            "в которых имя упомянуто (например, угрозы в адрес названного человека). "
            "Система не строит профиль, не ищет аккаунты и не связывает сведения между платформами."
        )
    return None
